"""
Compare reference MD displacement distributions with four inference stages.

Target:
    Diffusing H atoms labelled He.

Outputs:
    01_MD_vs_prior_raw_xyz.png
    02_MD_vs_before_corrector_xyz.png
    03_MD_vs_after_corrector_xyz.png
    04_MD_vs_final_xyz.png

Each PNG contains x, y and z component histograms.

MD coordinates must already be unwrapped.
No PBC correction is applied by this script.
"""

import re
from collections import deque
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


# ============================================================
# User parameters
# ============================================================

md_xyz_path = Path("output.xyz")

# CSV generated by the modified inference.py.
# Multiple CSVs may be combined only when simulation settings match.
inference_csv_paths = [
    Path("../../../scripts/flow_debug_ov2ng35_/he_displacements.csv"),
]

# Select every He-labelled atom in the reference MD.
md_target_species = "He"
expected_target_atom_count = 2

# None: use all atom indices recorded in the CSV.
# The generated he_displacements.csv contains only He-labelled atoms.
# Example for explicit selection: [31, 73]
csv_atom_indices = None

# None: use every run_id in each CSV.
# Example: [0]
csv_run_ids = None

# Reference MD displacement interval.
lag_frames = 50
time_step_ps = 0.01
dump_stride = 1

# Plot settings.
bins = 80
x_limits = (-10.0, 10.0)
chunksize = 100_000

output_dir = Path("displacement_stage_comparison")

md_label = "Reference MD (all diffusing H)"
md_color = "#7166ff"
inference_color = "#ff6666"

figure_size = (18.0, 5.4)
dpi = 180

# ============================================================


STAGES = [
    {
        "prefix": "prior_raw",
        "label": "Initial prior (before scaling / transform)",
        "title": "Reference MD vs initial prior",
        "filename": "01_MD_vs_prior_raw_xyz.png",
    },
    {
        "prefix": "before_corrector",
        "label": "Before Corrector",
        "title": "Reference MD vs before Corrector",
        "filename": "02_MD_vs_before_corrector_xyz.png",
    },
    {
        "prefix": "after_corrector",
        "label": "After Corrector (before COM removal)",
        "title": "Reference MD vs after Corrector",
        "filename": "03_MD_vs_after_corrector_xyz.png",
    },
    {
        "prefix": "final",
        "label": "Final (after COM removal)",
        "title": "Reference MD vs final displacement",
        "filename": "04_MD_vs_final_xyz.png",
    },
]


def iter_xyz_frames(path):
    """Read species and xyz coordinates from a conventional XYZ file."""
    with path.open("r", encoding="utf-8") as f:
        frame_index = 0

        while True:
            line = f.readline()

            if not line:
                return

            line = line.strip()

            if not line:
                continue

            if not re.fullmatch(r"\d+", line):
                raise ValueError(
                    f"Invalid atom-count line in {path}, "
                    f"frame={frame_index}: {line!r}"
                )

            natoms = int(line)

            if natoms < 1:
                raise ValueError(
                    f"Invalid atom count in {path}: {natoms}"
                )

            comment = f.readline()

            if not comment:
                raise ValueError(
                    f"Incomplete XYZ frame in {path}: missing comment"
                )

            species = []
            positions = np.empty((natoms, 3), dtype=float)

            for atom_index in range(natoms):
                parts = f.readline().split()

                if len(parts) < 4:
                    raise ValueError(
                        f"Bad atom line in {path}: "
                        f"frame={frame_index}, atom={atom_index}"
                    )

                species.append(parts[0])

                try:
                    positions[atom_index] = [
                        float(value) for value in parts[1:4]
                    ]
                except ValueError as exc:
                    raise ValueError(
                        f"Invalid coordinates in {path}: "
                        f"frame={frame_index}, atom={atom_index}"
                    ) from exc

            yield species, positions
            frame_index += 1


def read_md_displacements(path, target_species, lag):
    """Pool lag-frame displacements of every target atom."""
    if not path.is_file():
        raise FileNotFoundError(f"MD XYZ not found: {path}")

    buffer = deque(maxlen=lag + 1)
    displacements = []

    reference_species = None
    atom_indices = None
    n_frames = 0

    for species, positions in iter_xyz_frames(path):
        if reference_species is None:
            reference_species = species.copy()
            atom_indices = [
                i
                for i, symbol in enumerate(species)
                if symbol == target_species
            ]

            if not atom_indices:
                raise ValueError(
                    f"No atoms labelled {target_species!r} in {path}"
                )

            if (
                expected_target_atom_count is not None
                and len(atom_indices) != expected_target_atom_count
            ):
                raise ValueError(
                    f"Expected {expected_target_atom_count} "
                    f"{target_species}-labelled atoms, "
                    f"but found {len(atom_indices)}: {atom_indices}"
                )

            print(
                f"[MD selection] species={target_species}, "
                f"atom_indices={atom_indices}, "
                f"n_atoms={len(atom_indices)}"
            )

        elif species != reference_species:
            raise ValueError(
                f"Atom count/order/species changed in {path}, "
                f"frame={n_frames}"
            )

        coordinates = positions[atom_indices].copy()

        if not np.isfinite(coordinates).all():
            raise ValueError(
                f"Nonfinite selected MD coordinates: frame={n_frames}"
            )

        buffer.append(coordinates)
        n_frames += 1

        if len(buffer) == lag + 1:
            displacements.append(buffer[-1] - buffer[0])

    if not displacements:
        raise ValueError(
            f"No MD displacement samples: "
            f"frames={n_frames}, lag_frames={lag}"
        )

    vectors = np.asarray(
        displacements, dtype=float
    ).reshape(-1, 3)

    if not np.isfinite(vectors).all():
        raise ValueError("MD displacements contain NaN or infinity")

    return vectors, n_frames, atom_indices


def read_inference_samples(paths):
    """Read the four stages using identical CSV rows for every stage."""
    components = {
        stage["prefix"]: [
            f"{stage['prefix']}_d{axis}" for axis in "xyz"
        ]
        for stage in STAGES
    }

    required = ["atom_index"]

    for columns in components.values():
        required.extend(columns)

    if csv_run_ids is not None:
        required.append("run_id")

    parts = {
        stage["prefix"]: [] for stage in STAGES
    }

    seen_paths = set()
    all_atom_indices = set()
    total_selected = 0

    for input_path in paths:
        path = Path(input_path)
        resolved = path.resolve()

        if resolved in seen_paths:
            raise ValueError(
                f"CSV specified more than once: {path}"
            )

        seen_paths.add(resolved)

        if not path.is_file():
            raise FileNotFoundError(
                f"Inference CSV not found: {path}"
            )

        columns = pd.read_csv(path, nrows=0).columns.tolist()
        missing = set(required) - set(columns)

        if missing:
            raise ValueError(
                f"Missing columns in {path}: {sorted(missing)}. "
                "Use he_displacements.csv generated by inference.py."
            )

        n_read = 0
        n_selected = 0
        file_atom_counts = {}

        for chunk in pd.read_csv(
            path,
            usecols=required,
            chunksize=chunksize,
        ):
            n_read += len(chunk)

            if csv_atom_indices is not None:
                chunk = chunk.loc[
                    chunk["atom_index"].isin(csv_atom_indices)
                ]

            if csv_run_ids is not None:
                chunk = chunk.loc[
                    chunk["run_id"].isin(csv_run_ids)
                ]

            if chunk.empty:
                continue

            atom_values = chunk["atom_index"].to_numpy(dtype=float)

            if (
                not np.isfinite(atom_values).all()
                or np.any(atom_values < 0)
                or np.any(atom_values != np.floor(atom_values))
            ):
                raise ValueError(
                    f"Invalid atom_index values in {path}"
                )

            for atom_index, count in (
                chunk["atom_index"].value_counts().items()
            ):
                atom_index = int(atom_index)
                file_atom_counts[atom_index] = (
                    file_atom_counts.get(atom_index, 0)
                    + int(count)
                )
                all_atom_indices.add(atom_index)

            for prefix, stage_columns in components.items():
                values = chunk[stage_columns].to_numpy(dtype=float)

                if not np.isfinite(values).all():
                    raise ValueError(
                        f"NaN or infinity in {path}, stage={prefix}"
                    )

                parts[prefix].append(values)

            n_selected += len(chunk)

        print(
            f"[CSV] {path}: rows={n_read:,}, "
            f"selected={n_selected:,}, "
            f"atom_counts={dict(sorted(file_atom_counts.items()))}"
        )

        if n_selected == 0:
            raise ValueError(
                f"No matching rows in CSV: {path}"
            )

        if (
            expected_target_atom_count is not None
            and len(file_atom_counts) != expected_target_atom_count
        ):
            raise ValueError(
                f"{path}: expected "
                f"{expected_target_atom_count} selected atoms, "
                f"found {len(file_atom_counts)}. "
                "Check csv_atom_indices."
            )

        total_selected += n_selected

    if total_selected == 0:
        raise ValueError("No inference samples were selected")

    samples = {
        prefix: np.concatenate(values, axis=0)
        for prefix, values in parts.items()
    }

    return samples, sorted(all_atom_indices)


def print_summary(label, vectors):
    means = np.mean(vectors, axis=0)
    stds = np.std(vectors, axis=0, ddof=0)
    rms = np.sqrt(np.mean(vectors ** 2, axis=0))

    print(
        f"\n[{label}] displacement vectors={len(vectors):,}"
    )

    for i, axis in enumerate("xyz"):
        print(
            f"  {axis}: "
            f"mean={means[i]:.6f} A, "
            f"std={stds[i]:.6f} A, "
            f"RMS={rms[i]:.6f} A"
        )


def make_common_edges(md_vectors, stage_samples):
    """Use identical full-data histogram edges in every output figure."""
    maximum = float(np.max(np.abs(md_vectors)))

    for vectors in stage_samples.values():
        maximum = max(
            maximum,
            float(np.max(np.abs(vectors))),
        )

    if x_limits is not None:
        maximum = max(
            maximum,
            abs(x_limits[0]),
            abs(x_limits[1]),
        )

    if maximum == 0:
        maximum = 1.0

    limit = float(np.nextafter(maximum, np.inf))
    return np.linspace(-limit, limit, bins + 1)


def make_common_y_limit(md_vectors, stage_samples, edges):
    """Use a common vertical scale for all figures and components."""
    maximum_density = 0.0

    for vectors in [md_vectors, *stage_samples.values()]:
        for axis_index in range(3):
            density, _ = np.histogram(
                vectors[:, axis_index],
                bins=edges,
                density=True,
            )
            maximum_density = max(
                maximum_density,
                float(density.max()),
            )

    return 1.10 * maximum_density if maximum_density > 0 else 1.0


def report_outside_display(label, vectors):
    if x_limits is None:
        return

    lo, hi = x_limits
    fractions = np.mean(
        (vectors < lo) | (vectors > hi),
        axis=0,
    )

    print(
        f"[Outside display] {label}: "
        + ", ".join(
            f"{axis}={100 * fractions[i]:.3f}%"
            for i, axis in enumerate("xyz")
        )
    )


def plot_stage(
    md_vectors,
    stage_vectors,
    stage,
    edges,
    y_limit,
    lag_ps,
):
    fig, axes = plt.subplots(
        1,
        3,
        figsize=figure_size,
        sharex=True,
        sharey=True,
    )

    for i, axis in enumerate("xyz"):
        ax = axes[i]

        ax.hist(
            md_vectors[:, i],
            bins=edges,
            density=True,
            color=md_color,
            alpha=0.68,
            label=md_label,
        )

        ax.hist(
            stage_vectors[:, i],
            bins=edges,
            density=True,
            color=inference_color,
            alpha=0.65,
            label=stage["label"],
        )

        ax.set_title(
            f"Component: Δ{axis}",
            fontsize=18,
        )
        ax.set_xlabel(
            f"Δ{axis} (Å)",
            fontsize=16,
        )
        ax.tick_params(labelsize=12)
        ax.grid(True, ls="--", alpha=0.35)
        ax.set_axisbelow(True)
        ax.set_ylim(0, y_limit)

        if x_limits is not None:
            ax.set_xlim(*x_limits)

    axes[0].set_ylabel(
        "Probability density (Å⁻¹)",
        fontsize=16,
    )

    fig.suptitle(
        f"{stage['title']} — diffusing H\n"
        f"MD lag = {lag_ps:g} ps; "
        f"samples per axis: MD={len(md_vectors):,}, "
        f"inference={len(stage_vectors):,}",
        fontsize=13,
    )

    handles, labels = axes[0].get_legend_handles_labels()

    fig.legend(
        handles,
        labels,
        loc="lower center",
        bbox_to_anchor=(0.5, 0.01),
        ncol=2,
        fontsize=12,
        frameon=False,
    )

    fig.tight_layout(
        rect=(0, 0.10, 1, 0.999),
        pad=1.0,
    )

    output_path = output_dir / stage["filename"]

    fig.savefig(
        output_path,
        dpi=dpi,
        bbox_inches="tight",
    )
    plt.close(fig)

    print(f"[Saved] {output_path}")


def main():
    if not inference_csv_paths:
        raise ValueError("inference_csv_paths is empty")

    if lag_frames < 1:
        raise ValueError("lag_frames must be >= 1")

    if (
        bins < 1
        or chunksize < 1
        or time_step_ps <= 0
        or dump_stride < 1
    ):
        raise ValueError(
            "bins, chunksize, time_step_ps and dump_stride "
            "must be positive"
        )

    if x_limits is not None:
        if (
            len(x_limits) != 2
            or not np.isfinite(x_limits).all()
            or x_limits[0] >= x_limits[1]
        ):
            raise ValueError(
                "x_limits must be None or a finite increasing pair"
            )

    if csv_atom_indices is not None and not csv_atom_indices:
        raise ValueError("csv_atom_indices must not be empty")

    if csv_run_ids is not None and not csv_run_ids:
        raise ValueError("csv_run_ids must not be empty")

    dt_frame_ps = time_step_ps * dump_stride
    lag_ps = lag_frames * dt_frame_ps

    md_vectors, n_frames, md_atom_indices = (
        read_md_displacements(
            md_xyz_path,
            md_target_species,
            lag_frames,
        )
    )

    stage_samples, selected_csv_atoms = read_inference_samples(
        inference_csv_paths
    )

    print(
        f"\n[MD] frames={n_frames:,}, "
        f"time_origins={n_frames - lag_frames:,}, "
        f"selected_atoms={md_atom_indices}"
    )
    print(
        f"[CSV selection] atom_indices={selected_csv_atoms}"
    )
    print(
        f"[Lag] {lag_frames} frames × "
        f"{dt_frame_ps:g} ps/frame = {lag_ps:g} ps"
    )
    print(
        "[PBC] No correction applied. "
        "Reference MD coordinates must be unwrapped."
    )

    if set(md_atom_indices) != set(selected_csv_atoms):
        print(
            "[WARNING] MD and CSV atom indices differ. "
            "This may be valid if atom ordering differs, "
            "but verify that both selections represent "
            "the same diffusing-H population."
        )

    print_summary(md_label, md_vectors)

    for stage in STAGES:
        print_summary(
            stage["label"],
            stage_samples[stage["prefix"]],
        )

    edges = make_common_edges(
        md_vectors,
        stage_samples,
    )
    y_limit = make_common_y_limit(
        md_vectors,
        stage_samples,
        edges,
    )

    print(
        f"\n[Histogram] common bins={bins}, "
        f"range=({edges[0]:.6g}, {edges[-1]:.6g}) A, "
        f"bin_width={edges[1] - edges[0]:.6g} A"
    )

    report_outside_display(md_label, md_vectors)

    for stage in STAGES:
        report_outside_display(
            stage["label"],
            stage_samples[stage["prefix"]],
        )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    for stage in STAGES:
        plot_stage(
            md_vectors=md_vectors,
            stage_vectors=stage_samples[stage["prefix"]],
            stage=stage,
            edges=edges,
            y_limit=y_limit,
            lag_ps=lag_ps,
        )

    print(f"\nCompleted: {len(STAGES)} PNG files.")
    print(f"Output directory: {output_dir.resolve()}")


if __name__ == "__main__":
    main()