# -*- coding: utf-8 -*-
"""
Compare reference MD and one-step Propagator displacement distributions.

Input:
    md_vs_propagator_one_step.csv
    generated by test_propagator_from_md.py

Target:
    Diffusing H atoms labelled He.
    Pool both target atoms over all selected starting structures.

Output:
    MD_vs_propagator_from_reference_md_xyz.png

The reference MD and generated displacement samples come from
the same set of starting structures.

This script does not read output.xyz.
No PBC correction or coordinate transformation is applied.
"""

import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


# ============================================================
# User parameters
# ============================================================

# Change this path to the actual comparison CSV.
comparison_csv_path = Path(
    "../../../scripts/"
    "propagator_from_reference_md_20261109_default/"
    "md_vs_propagator_one_step.csv"
)

# Automatically read run_settings.json beside the comparison CSV.
settings_json_path = (
    comparison_csv_path.parent / "run_settings.json"
)

# None: select every atom recorded in the CSV.
# The generated comparison CSV contains only the target He-labelled H.
# Example: [165, 166]
csv_atom_indices = None

# None: use every starting structure.
# Example: [0, 1, 2]
csv_origin_ids = None

expected_target_atom_count = 2

# Used only when run_settings.json is unavailable.
fallback_lag_ps = 0.5

# Plot settings.
bins = 80
x_limits = (-10.0, 10.0)

# Set a pair such as (0.0, 0.65) to match a previous figure.
# None: automatically determine a common range for xyz.
y_limits = None

output_dir = Path(
    "propagator_from_reference_md_comparison_default"
)
output_png_name = (
    "MD_vs_propagator_from_reference_md_xyz.png"
)

md_label = "Reference MD (selected starting structures)"
prediction_label = "Propagator from reference MD"

md_color = "#7166ff"
prediction_color = "#ff6666"

figure_size = (18.0, 5.4)
dpi = 180

# Simple summary of large-displacement frequency.
large_displacement_threshold_A = 4.0

# ============================================================


MD_COLUMNS = [
    "md_dx",
    "md_dy",
    "md_dz",
]

PREDICTION_COLUMNS = [
    "pred_dx",
    "pred_dy",
    "pred_dz",
]


def validate_parameters():
    if not comparison_csv_path.is_file():
        raise FileNotFoundError(
            "Comparison CSV not found: "
            f"{comparison_csv_path.resolve()}"
        )

    if not isinstance(bins, int) or bins < 1:
        raise ValueError("bins must be an integer >= 1")

    for name, limits in (
        ("x_limits", x_limits),
        ("y_limits", y_limits),
    ):
        if limits is not None:
            if (
                len(limits) != 2
                or not np.isfinite(limits).all()
                or limits[0] >= limits[1]
            ):
                raise ValueError(
                    f"{name} must be None or "
                    "a finite increasing pair"
                )

    if csv_atom_indices is not None:
        if len(csv_atom_indices) == 0:
            raise ValueError(
                "csv_atom_indices must not be empty"
            )

    if csv_origin_ids is not None:
        if len(csv_origin_ids) == 0:
            raise ValueError(
                "csv_origin_ids must not be empty"
            )

    if (
        not np.isfinite(fallback_lag_ps)
        or fallback_lag_ps <= 0
    ):
        raise ValueError(
            "fallback_lag_ps must be finite and positive"
        )

    if (
        not np.isfinite(large_displacement_threshold_A)
        or large_displacement_threshold_A <= 0
    ):
        raise ValueError(
            "large_displacement_threshold_A "
            "must be finite and positive"
        )


def read_settings():
    if not settings_json_path.is_file():
        print(
            "[Settings] run_settings.json not found. "
            f"Using fallback lag={fallback_lag_ps:g} ps."
        )
        return {}, float(fallback_lag_ps)

    with settings_json_path.open(
        "r",
        encoding="utf-8",
    ) as f:
        settings = json.load(f)

    lag_ps = float(
        settings.get("lag_ps", fallback_lag_ps)
    )

    if not np.isfinite(lag_ps) or lag_ps <= 0:
        raise ValueError(
            f"Invalid lag_ps in {settings_json_path}"
        )

    status = settings.get("status")

    if status is not None and status != "completed":
        print(
            f"[WARNING] Recorded run status={status!r}. "
            "The CSV may contain only partial results."
        )

    print(
        f"[Settings] {settings_json_path.resolve()}"
    )
    print(
        "[Settings] "
        f"lag={lag_ps:g} ps, "
        f"temperature={settings.get('temperature_K', 'unknown')} K, "
        f"completed_origins="
        f"{settings.get('completed_origins', 'unknown')}"
    )

    return settings, lag_ps


def read_comparison_samples(path):
    required = [
        "origin_id",
        "run_id",
        "start_frame",
        "end_frame",
        "atom_index",
        *MD_COLUMNS,
        *PREDICTION_COLUMNS,
    ]

    columns = pd.read_csv(
        path,
        nrows=0,
    ).columns.tolist()

    missing = set(required) - set(columns)

    if missing:
        raise ValueError(
            f"Missing columns in {path}: {sorted(missing)}. "
            "Use md_vs_propagator_one_step.csv, "
            "not he_displacements.csv."
        )

    df = pd.read_csv(
        path,
        usecols=required,
    )

    n_read = len(df)

    if csv_atom_indices is not None:
        df = df.loc[
            df["atom_index"].isin(csv_atom_indices)
        ]

    if csv_origin_ids is not None:
        df = df.loc[
            df["origin_id"].isin(csv_origin_ids)
        ]

    df = df.copy()

    if df.empty:
        raise ValueError(
            "No matching displacement samples were selected"
        )

    integer_columns = [
        "origin_id",
        "run_id",
        "start_frame",
        "end_frame",
        "atom_index",
    ]

    for column in integer_columns:
        values = df[column].to_numpy(dtype=float)

        if (
            not np.isfinite(values).all()
            or np.any(values < 0)
            or np.any(values != np.floor(values))
        ):
            raise ValueError(
                f"Invalid integer values in column: {column}"
            )

        df[column] = df[column].astype(np.int64)

    if df.duplicated(
        subset=["origin_id", "atom_index"]
    ).any():
        raise ValueError(
            "Duplicate origin_id / atom_index rows were found"
        )

    selected_atoms = sorted(
        df["atom_index"].unique().tolist()
    )

    if (
        expected_target_atom_count is not None
        and len(selected_atoms) != expected_target_atom_count
    ):
        raise ValueError(
            f"Expected {expected_target_atom_count} target atoms, "
            f"found {len(selected_atoms)}: {selected_atoms}"
        )

    atoms_per_origin = df.groupby(
        "origin_id"
    )["atom_index"].nunique()

    if not atoms_per_origin.eq(
        len(selected_atoms)
    ).all():
        raise ValueError(
            "Some starting structures are missing target-atom rows"
        )

    for column in (
        "run_id",
        "start_frame",
        "end_frame",
    ):
        counts = df.groupby(
            "origin_id"
        )[column].nunique()

        if not counts.eq(1).all():
            raise ValueError(
                f"Inconsistent {column} within an origin_id"
            )

    frame_lags = (
        df["end_frame"] - df["start_frame"]
    )

    if (frame_lags <= 0).any():
        raise ValueError(
            "end_frame must be greater than start_frame"
        )

    if frame_lags.nunique() != 1:
        raise ValueError(
            "Different displacement intervals are mixed in the CSV"
        )

    md_vectors = df[MD_COLUMNS].to_numpy(
        dtype=float
    )
    prediction_vectors = df[
        PREDICTION_COLUMNS
    ].to_numpy(dtype=float)

    if not np.isfinite(md_vectors).all():
        raise ValueError(
            "Reference MD samples contain NaN or infinity"
        )

    if not np.isfinite(prediction_vectors).all():
        raise ValueError(
            "Prediction samples contain NaN or infinity"
        )

    n_origins = df["origin_id"].nunique()

    print(
        f"\n[CSV] {path.resolve()}"
    )
    print(
        f"[Selection] rows_read={n_read:,}, "
        f"rows_selected={len(df):,}"
    )
    print(
        f"[Selection] atom_indices={selected_atoms}, "
        f"starting_structures={n_origins:,}"
    )
    print(
        "[Samples] "
        f"{n_origins:,} starting structures "
        f"× {len(selected_atoms)} atoms "
        f"= {len(md_vectors):,} vectors per dataset"
    )
    print(
        "[Frame interval] "
        f"{int(frame_lags.iloc[0])} frames"
    )

    return df, md_vectors, prediction_vectors


def print_summary(label, vectors):
    means = np.mean(vectors, axis=0)
    stds = np.std(vectors, axis=0, ddof=0)
    rms = np.sqrt(
        np.mean(vectors ** 2, axis=0)
    )

    magnitudes = np.linalg.norm(
        vectors,
        axis=1,
    )

    large_fraction = np.mean(
        magnitudes > large_displacement_threshold_A
    )

    print(
        f"\n[{label}] vectors={len(vectors):,}"
    )

    for i, axis in enumerate("xyz"):
        print(
            f"  {axis}: "
            f"mean={means[i]:.6f} A, "
            f"std={stds[i]:.6f} A, "
            f"RMS={rms[i]:.6f} A"
        )

    print(
        "  P(|displacement| > "
        f"{large_displacement_threshold_A:g} A)"
        f"={large_fraction:.6f}"
    )


def make_common_edges(
    md_vectors,
    prediction_vectors,
):
    """Include all samples in the histogram normalization."""
    maximum = max(
        float(np.max(np.abs(md_vectors))),
        float(np.max(np.abs(prediction_vectors))),
    )

    if x_limits is not None:
        maximum = max(
            maximum,
            abs(x_limits[0]),
            abs(x_limits[1]),
        )

    if maximum == 0:
        maximum = 1.0

    limit = float(
        np.nextafter(maximum, np.inf)
    )

    return np.linspace(
        -limit,
        limit,
        bins + 1,
    )


def make_common_y_limits(
    md_vectors,
    prediction_vectors,
    edges,
):
    if y_limits is not None:
        return y_limits

    maximum_density = 0.0

    for vectors in (
        md_vectors,
        prediction_vectors,
    ):
        for axis_index in range(3):
            density, _ = np.histogram(
                vectors[:, axis_index],
                bins=edges,
                density=True,
            )

            maximum_density = max(
                maximum_density,
                float(density.max()),
            )

    upper = (
        1.10 * maximum_density
        if maximum_density > 0
        else 1.0
    )

    return (0.0, upper)


def report_outside_display(label, vectors):
    if x_limits is None:
        return

    lo, hi = x_limits

    fractions = np.mean(
        (vectors < lo) | (vectors > hi),
        axis=0,
    )

    print(
        f"[Outside display] {label}: "
        + ", ".join(
            f"{axis}={100 * fractions[i]:.3f}%"
            for i, axis in enumerate("xyz")
        )
    )


def plot_comparison(
    md_vectors,
    prediction_vectors,
    n_origins,
    lag_ps,
    edges,
    plot_y_limits,
):
    fig, axes = plt.subplots(
        1,
        3,
        figsize=figure_size,
        sharex=True,
        sharey=True,
    )

    for i, axis in enumerate("xyz"):
        ax = axes[i]

        ax.hist(
            md_vectors[:, i],
            bins=edges,
            density=True,
            color=md_color,
            alpha=0.68,
            label=md_label,
        )

        ax.hist(
            prediction_vectors[:, i],
            bins=edges,
            density=True,
            color=prediction_color,
            alpha=0.65,
            label=prediction_label,
        )

        ax.set_title(
            f"Component: Δ{axis}",
            fontsize=18,
        )

        ax.set_xlabel(
            f"Δ{axis} (Å)",
            fontsize=16,
        )

        ax.tick_params(labelsize=12)
        ax.grid(
            True,
            ls="--",
            alpha=0.35,
        )
        ax.set_axisbelow(True)
        ax.set_ylim(*plot_y_limits)

        if x_limits is not None:
            ax.set_xlim(*x_limits)

    axes[0].set_ylabel(
        "Probability density (Å⁻¹)",
        fontsize=16,
    )

    fig.suptitle(
        "Reference MD vs one-step Propagator "
        "from reference MD structures — diffusing H\n"
        f"Lag = {lag_ps:g} ps; "
        f"starting structures = {n_origins:,}; "
        f"samples per axis: "
        f"MD={len(md_vectors):,}, "
        f"prediction={len(prediction_vectors):,}",
        fontsize=13,
    )

    handles, labels = (
        axes[0].get_legend_handles_labels()
    )

    fig.legend(
        handles,
        labels,
        loc="lower center",
        bbox_to_anchor=(0.5, 0.01),
        ncol=2,
        fontsize=12,
        frameon=False,
    )

    fig.tight_layout(
        rect=(0, 0.10, 1, 0.999),
        pad=1.0,
    )

    output_path = (
        output_dir / output_png_name
    )

    fig.savefig(
        output_path,
        dpi=dpi,
        bbox_inches="tight",
    )
    plt.close(fig)

    print(
        f"\n[Saved] {output_path.resolve()}"
    )


def main():
    validate_parameters()

    settings, lag_ps = read_settings()

    df, md_vectors, prediction_vectors = (
        read_comparison_samples(
            comparison_csv_path
        )
    )

    csv_lag_frames = int(
        (
            df["end_frame"]
            - df["start_frame"]
        ).iloc[0]
    )

    if "lag_frames" in settings:
        if csv_lag_frames != int(
            settings["lag_frames"]
        ):
            raise ValueError(
                "CSV displacement interval differs "
                "from run_settings.json"
            )

    if "target_atom_indices" in settings:
        selected = set(
            df["atom_index"].unique().tolist()
        )
        recorded = set(
            settings["target_atom_indices"]
        )

        if not selected.issubset(recorded):
            raise ValueError(
                "Selected atom indices disagree "
                "with run_settings.json"
            )

    print_summary(
        md_label,
        md_vectors,
    )
    print_summary(
        prediction_label,
        prediction_vectors,
    )

    md_stds = np.std(
        md_vectors,
        axis=0,
        ddof=0,
    )
    prediction_stds = np.std(
        prediction_vectors,
        axis=0,
        ddof=0,
    )

    ratios = np.divide(
        prediction_stds,
        md_stds,
        out=np.full(3, np.nan),
        where=md_stds > 0,
    )

    print(
        "\n[Width ratio] std(prediction) / std(MD)"
    )

    for i, axis in enumerate("xyz"):
        print(
            f"  {axis}: {ratios[i]:.6f}"
        )

    edges = make_common_edges(
        md_vectors,
        prediction_vectors,
    )

    plot_y_limits = make_common_y_limits(
        md_vectors,
        prediction_vectors,
        edges,
    )

    print(
        f"\n[Histogram] bins={bins}, "
        f"range=({edges[0]:.6g}, {edges[-1]:.6g}) A, "
        f"bin_width={edges[1] - edges[0]:.6g} A"
    )

    report_outside_display(
        md_label,
        md_vectors,
    )
    report_outside_display(
        prediction_label,
        prediction_vectors,
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    plot_comparison(
        md_vectors=md_vectors,
        prediction_vectors=prediction_vectors,
        n_origins=df["origin_id"].nunique(),
        lag_ps=lag_ps,
        edges=edges,
        plot_y_limits=plot_y_limits,
    )

    print(
        "\nCompleted: 1 PNG file."
    )
    print(
        "Output directory: "
        f"{output_dir.resolve()}"
    )


if __name__ == "__main__":
    main()